const takeWebHostnameEffect = Effect.fnUntraced(function* (
  assignment: Pick<InstanceDomainAssignment, "instanceId" | "relayId">,
  hostname: string
) {
  const database = yield* Database
  const [held] = yield* database.queryRows<
    RowDataPacket & { id: string; routed: boolean | number }
  >(
    "domains.assignment.takeWebHostname",
    `SELECT id, routed FROM ${addressTable}
      WHERE hostname = ? AND game = 0 AND relay_id = ?
        AND resource_type = 'instance' AND resource_id = ?
      FOR UPDATE`,
    [hostname, assignment.relayId, assignment.instanceId]
  )
  if (!held) return false
  yield* database.execute(
    "domains.assignment.takeWebHostname",
    `DELETE FROM ${addressTable} WHERE id = ?`,
    [held.id]
  )
  return Boolean(held.routed)
})


/**
 * Puts off a game server's domains that still need work after an attempt,
 * each time twice as long, up to an hour.
 */
export const deferInstanceDomainsEffect = Effect.fn(
  "domains.assignments.defer"
)(function* (relayId: string, instanceId: string, now: number) {
  const database = yield* Database
  yield* database.execute(
    "domains.assignments.defer",
    `UPDATE ${addressTable}
          SET next_attempt_at = ? + LEAST(3600000, 30000 * POW(2, attempts)),
              attempts = LEAST(attempts + 1, 60)
        WHERE relay_id = ? AND resource_type = 'instance' AND resource_id = ?
          AND ${assignmentNeedsWork}`,
    [now, relayId, instanceId]
  )
})

// An active domain with an error is one whose records didn't follow its
// game server's endpoint.
const assignmentNeedsWork = `(game = 1
  AND (status IN ('pending', 'error', 'removing')
    OR next_hostname IS NOT NULL OR last_error IS NOT NULL))`

function domainAssignment(row: InstanceDomainRow): InstanceDomainAssignment {
  const domain = row.vanity_domain ?? ""
  // A name under its vanity domain: the label is what comes before it.
  const label = (hostname: string, under: string) =>
    hostname.slice(0, hostname.length - under.length - 1)
  return {
    addressRecordId: row.record_id,
    addressRecordType: row.record_type,
    domain,
    id: row.id,
    instanceId: row.instance_id,
    integrationId: row.integration_id,
    lastError: row.last_error,
    next:
      row.next_hostname && row.next_vanity_domain
        ? {
            domain: row.next_vanity_domain,
            vanityLabel: label(row.next_hostname, row.next_vanity_domain),
          }
        : null,
    primary: Boolean(row.is_primary),
    publicHost: row.target ?? "",
    publicPort: row.public_port ?? 0,
    relayId: row.relay_id,
    srvProtocol: row.srv_protocol,
    srvRecordId: row.srv_record_id,
    srvService: row.srv_service,
    status: row.status,
    supportsSrv: Boolean(row.supports_srv),
    vanityLabel: label(row.hostname, domain),
    zoneId: row.zone_id,
  }
}

// One row per hostname an instance holds, whatever it is used for: a game
// server's address, which points at its game port (`game`), a name web
// routes answer on (`routed`), or the address Kiln made an App
// (`is_generated`). A game server's web route on its own address is that
// address's row with both.
//
// Two views read and write it. A game server's addresses are the rows with
// `game = 1`: while it is one, its record is the address's, pointing at
// the game server's public host, never proxied, with its SRV record. A
// resource's web hostnames are the rows with `game = 0 OR routed = 1`: of
// an address's row the web side only says whether routes use it, and
// reports it in step.
const addressTable = databaseTable("instance_address")
const webUse = "(game = 0 OR routed = 1)"

export type WebHostnameResourceType = HostnameOwner["resourceType"]

/**
 * The address record Cloudflare already had under a hostname, that Kiln
 * didn't make, as Kiln last saw it.
 */
export interface ExistingWebRecord {
  content: string
  id: string
  proxied: boolean
  type: "A" | "AAAA" | "CNAME"
}

/**
 * A web hostname whose DNS record Kiln keeps in Cloudflare, pointing at the
 * Relay its game server or app runs on.
 */
export interface WebHostname {
  /** The connection whose token manages its zone. */
  connectionId: string
  createdAt: number
  /**
   * While `external`, the address record Cloudflare had under the name, as
   * Kiln last saw it; null when it had none, only other kinds of record.
   */
  existingRecord: ExistingWebRecord | null
  /**
   * Its game server's address too. Its record is the address's then, so it
   * reads here as in step with none of its own.
   */
  game: boolean
  /** Generated by Kiln as an app's address, kept without a route. */
  generated: boolean
  /** Used by the resource's web routes as last saved. */
  routed: boolean
  hostname: string
  id: string
  lastError: string | null
  /** Whether Kiln keeps its record behind Cloudflare's proxy. */
  proxied: boolean
  recordId: string | null
  recordType: "A" | "AAAA" | "CNAME" | null
  relayId: string
  resourceId: string
  resourceType: WebHostnameResourceType
  /**
   * `external` when Cloudflare already had a record Kiln didn't make; Kiln
   * leaves it alone and checks again on the next sync.
   */
  status: "active" | "error" | "external" | "pending" | "removing"
  /** What the record points at: the Relay's public address. */
  target: string | null
  /** The vanity domain it's named under, when it is. */
  vanityDomain: string | null
  zoneId: string
}

export type WebHostnameResource = HostnameOwner

/**
 * Whether a hostname's record goes through Cloudflare's proxy, as Kiln
 * keeps it or last saw someone else's; null when that's unknown. A game
 * server's own address keeps its domain's record, which never does.
 */
export function webHostnameProxied(
  row: Pick<WebHostname, "existingRecord" | "proxied" | "recordId" | "status">
): boolean | null {
  if (row.status === "external") return row.existingRecord?.proxied ?? null
  if (row.status === "active" && !row.recordId) return false
  return row.proxied
}

interface WebHostnameRow extends RowDataPacket {
  created_at: number
  game: boolean | number
  existing_record_content: string | null
  existing_record_id: string | null
  existing_record_proxied: boolean | number | null
  existing_record_type: "A" | "AAAA" | "CNAME" | null
  hostname: string
  id: string
  integration_id: string
  is_generated: boolean | number
  last_error: string | null
  proxied: boolean | number
  routed: boolean | number
  record_id: string | null
  record_type: "A" | "AAAA" | "CNAME" | null
  relay_id: string
  resource_id: string
  resource_type: WebHostnameResourceType
  status: WebHostname["status"]
  target: string | null
  vanity_domain: string | null
  zone_id: string | null
}

const webHostnameSelect = `SELECT id, hostname, relay_id, resource_type,
       resource_id, integration_id, zone_id, vanity_domain, game,
       is_generated, routed, record_id, record_type, target, proxied,
       existing_record_id, existing_record_type, existing_record_content,
       existing_record_proxied, status, last_error, created_at
  FROM ${addressTable}`

export const loadWebHostnameEffect = Effect.fn("webHostnames.load")(function* (
  id: string
) {
  const database = yield* Database
  const rows = yield* database.queryRows<WebHostnameRow>(
    "webHostnames.load",
    `${webHostnameSelect} WHERE id = ? AND ${webUse} LIMIT 1`,
    [id]
  )
  const row = rows[0]
  return row ? webHostname(row) : null
})


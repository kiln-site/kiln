/** Every hostname, or one Relay's or one connection's. */
export const listWebHostnamesEffect = Effect.fn("webHostnames.list")(
  function* (filter?: { connectionId?: string; relayId?: string }) {
    const database = yield* Database
    const conditions: Array<string> = [webUse]
    const values: Array<string> = []
    if (filter?.relayId) {
      conditions.push("relay_id = ?")
      values.push(filter.relayId)
    }
    if (filter?.connectionId) {
      conditions.push("integration_id = ?")
      values.push(filter.connectionId)
    }
    const rows = yield* database.queryRows<WebHostnameRow>(
      "webHostnames.list",
      `${webHostnameSelect}
        WHERE ${conditions.join(" AND ")}
        ORDER BY hostname`,
      values
    )
    return rows.map(webHostname)
  }
)

/**
 * Holds a hostname for a resource before its record exists, claiming it in
 * the same transaction. A hostname another resource holds fails rather than
 * being taken over.
 */
export const insertWebHostnameEffect = Effect.fn("webHostnames.insert")(
  function* (
    input: WebHostnameResource & {
      connectionId: string
      generated: boolean
      hostname: string
      id: string
      vanityDomain: string | null
      zoneId: string
    }
  ) {
    const database = yield* Database
    const now = yield* Clock.currentTimeMillis
    yield* database.transaction("webHostnames.insert", () =>
      Effect.gen(function* () {
        // A connection removed since its zone was resolved takes no new
        // hostnames; removing one waits for this insert, then deletes it.
        const connections = yield* database.queryRows<RowDataPacket>(
          "webHostnames.insert",
          `SELECT 1 FROM ${databaseTable("domain_integration")}
            WHERE id = ?
            LOCK IN SHARE MODE`,
          [input.connectionId]
        )
        if (connections.length === 0) {
          return yield* DomainConfigurationError.make({
            message: "The Cloudflare connection for this hostname was removed",
          })
        }
        yield* claimHostnamesEffect(input, [input.hostname])
        yield* database.execute(
          "webHostnames.insert",
          `INSERT INTO ${addressTable}
             (id, hostname, relay_id, resource_type, resource_id,
              integration_id, zone_id, vanity_domain, is_generated, status,
              created_at, updated_at)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, 'pending', ?, ?)`,
          [
            input.id,
            input.hostname.toLowerCase(),
            input.relayId,
            input.resourceType,
            input.resourceId,
            input.connectionId,
            input.zoneId,
            input.vanityDomain,
            input.generated,
            now,
            now,
          ]
        )
      })
    )
  }
)


/**
 * Sets whether a resource's hostnames go through Cloudflare's proxy. A
 * record Kiln keeps that changes waits for the next sync, as a new one
 * does.
 */
export const setWebHostnamesProxiedEffect = Effect.fn("webHostnames.proxied")(
  function* (
    resource: WebHostnameResource,
    hostnames: ReadonlyArray<string>,
    proxied: boolean
  ) {
    const names = [...new Set(hostnames.map((name) => name.toLowerCase()))]
    if (names.length === 0) return
    const database = yield* Database
    const now = yield* Clock.currentTimeMillis
    yield* database.execute(
      "webHostnames.proxied",
      `UPDATE ${addressTable}
          SET proxied = ?,
              status = IF(status = 'active' AND record_id IS NOT NULL,
                'pending', status),
              attempts = 0, next_attempt_at = NULL, updated_at = ?
        WHERE relay_id = ? AND resource_type = ? AND resource_id = ?
          AND game = 0 AND proxied <> ?
          AND hostname IN (${names.map(() => "?").join(", ")})`,
      [
        proxied,
        now,
        resource.relayId,
        resource.resourceType,
        resource.resourceId,
        proxied,
        ...names,
      ]
    )
  }
)

/**
 * Marks hostnames a resource's routes no longer use for deletion. Each keeps
 * its claim until its record is gone; the DNS worker finishes any a request
 * doesn't. One that is its game server's address only stops being routed.
 */
export const markWebHostnamesRemovingEffect = Effect.fn(
  "webHostnames.markRemoving"
)(function* (ids: ReadonlyArray<string>) {
  if (ids.length === 0) return
  const database = yield* Database
  const now = yield* Clock.currentTimeMillis
  const named = `id IN (${ids.map(() => "?").join(", ")})`
  yield* database.execute(
    "webHostnames.markRemoving",
    `UPDATE ${addressTable}
        SET status = 'removing', last_error = NULL, attempts = 0,
            next_attempt_at = NULL, updated_at = ?
      WHERE ${named} AND game = 0`,
    [now, ...ids]
  )
  yield* database.execute(
    "webHostnames.markRemoving",
    `UPDATE ${addressTable} SET routed = 0 WHERE ${named} AND game = 1`,
    [...ids]
  )
})


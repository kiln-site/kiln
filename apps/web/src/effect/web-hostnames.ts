// A game server's web route on a name one of its domains also uses.
const sharedWithDomain = `used.resource_type = 'instance' AND EXISTS (
  SELECT 1 FROM ${databaseTable("instance_domain")} domain
   WHERE domain.relay_id = used.relay_id
     AND domain.instance_id = used.resource_id
     AND (CONCAT(domain.vanity_label, '.', domain.domain) = used.hostname
       OR CONCAT(domain.next_vanity_label, '.', domain.next_domain)
          = used.hostname))`

// A hostname a failed save claimed waits for a save, not the worker.
const webHostnameNeedsWork = `(status = 'removing' OR (
  status IN ('pending', 'error')
  AND (routed = 1 OR is_generated = 1 OR record_id IS NOT NULL)))`

function webHostname(row: WebHostnameRow): WebHostname {
  return {
    connectionId: row.integration_id,
    createdAt: Number(row.created_at),
    generated: Boolean(row.is_generated),
    hostname: row.hostname,
    id: row.id,
    lastError: row.last_error,
    recordId: row.record_id,
    routed: Boolean(row.routed),
    recordType: row.record_type,
    relayId: row.relay_id,
    resourceId: row.resource_id,
    resourceType: row.resource_type,
    status: row.status,
    target: row.target,
    vanityDomain: row.vanity_domain,
    zoneId: row.zone_id,
  }
}

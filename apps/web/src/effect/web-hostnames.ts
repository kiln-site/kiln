/** A game server's or app's hostnames, generated first, then by name. */
export const listResourceWebHostnamesEffect = Effect.fn(
  "webHostnames.resource"
)(function* (resource: WebHostnameResource) {
  const database = yield* Database
  const rows = yield* database.queryRows<WebHostnameRow>(
    "webHostnames.resource",
    `${webHostnameSelect}
      WHERE relay_id = ? AND resource_type = ? AND resource_id = ?
      ORDER BY is_generated DESC, hostname`,
    [resource.relayId, resource.resourceType, resource.resourceId]
  )
  return rows.map(webHostname)
})

/** Every hostname, or one Relay's or one connection's. */
export const listWebHostnamesEffect = Effect.fn("webHostnames.list")(
  function* (filter?: { connectionId?: string; relayId?: string }) {
    const database = yield* Database
    const conditions: Array<string> = []
    const values: Array<string> = []
    if (filter?.relayId) {
      conditions.push("relay_id = ?")
      values.push(filter.relayId)
    }
    if (filter?.connectionId) {
      conditions.push("integration_id = ?")
      values.push(filter.connectionId)
    }
    const rows = yield* database.queryRows<WebHostnameRow>(
      "webHostnames.list",
      `${webHostnameSelect}
        ${conditions.length > 0 ? `WHERE ${conditions.join(" AND ")}` : ""}
        ORDER BY hostname`,
      values
    )
    return rows.map(webHostname)
  }
)

/**
 * Holds a hostname for a resource before its record exists, claiming it in
 * the same transaction. A hostname another resource holds fails rather than
 * being taken over.
 */
export const insertWebHostnameEffect = Effect.fn("webHostnames.insert")(
  function* (
    input: WebHostnameResource & {
      connectionId: string
      generated: boolean
      hostname: string
      id: string
      vanityDomain: string | null
      zoneId: string
    }
  ) {
    const database = yield* Database
    const now = yield* Clock.currentTimeMillis
    yield* database.transaction("webHostnames.insert", () =>
      Effect.gen(function* () {
        // A connection removed since its zone was resolved takes no new
        // hostnames; removing one waits for this insert, then deletes it.
        const connections = yield* database.queryRows<RowDataPacket>(
          "webHostnames.insert",
          `SELECT 1 FROM ${databaseTable("domain_integration")}
            WHERE id = ?
            FOR SHARE`,
          [input.connectionId]
        )
        if (connections.length === 0) {
          return yield* DomainConfigurationError.make({
            message: "The Cloudflare connection for this hostname was removed",
          })
        }
        yield* claimHostnamesEffect(input, [input.hostname])
        yield* database.execute(
          "webHostnames.insert",
          `INSERT INTO ${databaseTable("web_hostname")}
             (id, hostname, relay_id, resource_type, resource_id,
              integration_id, zone_id, vanity_domain, is_generated, status,
              created_at, updated_at)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, 'pending', ?, ?)`,
          [
            input.id,
            input.hostname.toLowerCase(),
            input.relayId,
            input.resourceType,
            input.resourceId,
            input.connectionId,
            input.zoneId,
            input.vanityDomain,
            input.generated,
            now,
            now,
          ]
        )
      })
    )
  }
)

/**
 * Records the DNS record Kiln made or updated for a hostname. False when the
 * hostname was let go or marked for deletion meanwhile, as removing its
 * Relay does, so the caller deletes a record it made.
 */
export const activateWebHostnameEffect = Effect.fn("webHostnames.activate")(
  function* (input: {
    id: string
    recordId: string
    recordType: "A" | "AAAA" | "CNAME"
    target: string
  }) {
    const database = yield* Database
    const now = yield* Clock.currentTimeMillis
    const result = yield* database.execute(
      "webHostnames.activate",
      `UPDATE ${databaseTable("web_hostname")}
          SET record_id = ?, record_type = ?, target = ?, status = 'active',
              last_error = NULL, attempts = 0, next_attempt_at = NULL,
              updated_at = ?
        WHERE id = ? AND status <> 'removing'`,
      [input.recordId, input.recordType, input.target, now, input.id]
    )
    return result.affectedRows > 0
  }
)

export const setWebHostnameStatusEffect = Effect.fn("webHostnames.setStatus")(
  function* (
    id: string,
    status: "error" | "external" | "pending" | "removing",
    message: string | null
  ) {
    const database = yield* Database
    const now = yield* Clock.currentTimeMillis
    yield* database.execute(
      "webHostnames.setStatus",
      // Work that finishes after a hostname was marked for deletion
      // leaves the mark.
      `UPDATE ${databaseTable("web_hostname")}
          SET status = ?, last_error = ?, updated_at = ?
        WHERE id = ? AND (status <> 'removing' OR ? = 'removing')`,
      [status, message?.slice(0, 512) ?? null, now, id, status]
    )
  }
)

/**
 * Marks hostnames a resource's routes no longer use for deletion. Each keeps
 * its claim until its record is gone; the DNS worker finishes any a request
 * doesn't.
 */
export const markWebHostnamesRemovingEffect = Effect.fn(
  "webHostnames.markRemoving"
)(function* (ids: ReadonlyArray<string>) {
  if (ids.length === 0) return
  const database = yield* Database
  const now = yield* Clock.currentTimeMillis
  yield* database.execute(
    "webHostnames.markRemoving",
    `UPDATE ${databaseTable("web_hostname")}
        SET status = 'removing', last_error = NULL, attempts = 0,
            next_attempt_at = NULL, updated_at = ?
      WHERE id IN (${ids.map(() => "?").join(", ")})`,
    [now, ...ids]
  )
})

/**
 * Whether a game server domain of the hostname's own game server names it,
 * now or as the name a rename is moving to. Its record is that domain's, so
 * the web hostname keeps none of its own meanwhile.
 */
export const webHostnameCoveredEffect = Effect.fn("webHostnames.covered")(
  function* (row: WebHostname) {
    if (row.resourceType !== "instance") return false
    const database = yield* Database
    const rows = yield* database.queryRows<RowDataPacket>(
      "webHostnames.covered",
      `SELECT 1 FROM ${databaseTable("instance_domain")}
        WHERE relay_id = ? AND instance_id = ?
          AND (CONCAT(vanity_label, '.', domain) = ?
            OR CONCAT(next_vanity_label, '.', next_domain) = ?)
        LIMIT 1`,
      [row.relayId, row.resourceId, row.hostname, row.hostname]
    )
    return rows.length > 0
  }
)

